/**
 * 포트폴리오 인터랙션 & 챗봇 스크립트
 * - 다크모드 토글 (localStorage 저장)
 * - 스크롤 내비게이션 스타일
 * - 섹션 등장 애니메이션 (IntersectionObserver)
 * - 부드러운 스크롤
 * - Upstage 기반 챗봇 (로컬 file: / 배포 환경 자동 분기)
 */

(function () {
  "use strict";

  /* ========== DOM 요소 참조 ========== */
  const nav = document.getElementById("nav");
  const themeToggle = document.getElementById("themeToggle");
  const navToggle = document.getElementById("navToggle");
  const navMenu = document.querySelector(".nav__menu");
  const revealElements = document.querySelectorAll(".reveal");

  const THEME_KEY = "portfolio-theme";


  /* ========== 다크모드 — 초기화 & 토글 ========== */
  function initTheme() {
    const saved = localStorage.getItem(THEME_KEY);

    if (saved === "dark") {
      document.documentElement.setAttribute("data-theme", "dark");
    } else if (saved === "light") {
      document.documentElement.removeAttribute("data-theme");
    } else if (window.matchMedia("(prefers-color-scheme: dark)").matches) {
      document.documentElement.setAttribute("data-theme", "dark");
    }
  }

  function toggleTheme() {
    const isDark = document.documentElement.getAttribute("data-theme") === "dark";

    if (isDark) {
      document.documentElement.removeAttribute("data-theme");
      localStorage.setItem(THEME_KEY, "light");
    } else {
      document.documentElement.setAttribute("data-theme", "dark");
      localStorage.setItem(THEME_KEY, "dark");
    }
  }

  initTheme();

  if (themeToggle) {
    themeToggle.addEventListener("click", toggleTheme);
  }


  /* ========== 스크롤 시 내비게이션 배경 ========== */
  function handleNavScroll() {
    if (!nav) return;

    if (window.scrollY > 40) {
      nav.classList.add("nav--scrolled");
    } else {
      nav.classList.remove("nav--scrolled");
    }
  }

  window.addEventListener("scroll", handleNavScroll, { passive: true });
  handleNavScroll();


  /* ========== 모바일 햄버거 메뉴 ========== */
  function closeMobileMenu() {
    if (!navMenu || !navToggle) return;
    navMenu.classList.remove("is-open");
    navToggle.classList.remove("is-active");
    navToggle.setAttribute("aria-expanded", "false");
    navToggle.setAttribute("aria-label", "메뉴 열기");
  }

  if (navToggle && navMenu) {
    navToggle.addEventListener("click", function () {
      const isOpen = navMenu.classList.toggle("is-open");
      navToggle.classList.toggle("is-active", isOpen);
      navToggle.setAttribute("aria-expanded", String(isOpen));
      navToggle.setAttribute("aria-label", isOpen ? "메뉴 닫기" : "메뉴 열기");
    });
  }


  /* ========== 내비 링크 — 부드러운 스크롤 ========== */
  function smoothScrollTo(targetId) {
    const target = document.querySelector(targetId);
    if (!target) return;

    const navHeight = nav ? nav.offsetHeight : 0;
    const top = target.getBoundingClientRect().top + window.scrollY - navHeight;

    window.scrollTo({
      top: top,
      behavior: "smooth",
    });
  }

  document.querySelectorAll('a[href^="#"]').forEach(function (anchor) {
    anchor.addEventListener("click", function (event) {
      const href = anchor.getAttribute("href");
      if (!href || href === "#") return;

      event.preventDefault();
      smoothScrollTo(href);
      closeMobileMenu();
    });
  });


  /* ========== IntersectionObserver — 섹션 등장 효과 ========== */
  if ("IntersectionObserver" in window && revealElements.length > 0) {
    const revealObserver = new IntersectionObserver(
      function (entries, observer) {
        entries.forEach(function (entry) {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-visible");
            observer.unobserve(entry.target);
          }
        });
      },
      {
        root: null,
        rootMargin: "0px 0px -60px 0px",
        threshold: 0.12,
      }
    );

    revealElements.forEach(function (el) {
      revealObserver.observe(el);
    });
  } else {
    revealElements.forEach(function (el) {
      el.classList.add("is-visible");
    });
  }


  /* ========== 히어로 — 페이지 로드 시 즉시 등장 ========== */
  var heroContent = document.querySelector(".hero .reveal");
  if (heroContent) {
    requestAnimationFrame(function () {
      heroContent.classList.add("is-visible");
    });
  }


  /* ============================================================
     챗봇
     ============================================================ */
  const chatFab = document.getElementById("chatFab");
  const chatPanel = document.getElementById("chatPanel");
  const chatClose = document.getElementById("chatClose");
  const chatMessages = document.getElementById("chatMessages");
  const chatForm = document.getElementById("chatForm");
  const chatInput = document.getElementById("chatInput");
  const chatSend = document.getElementById("chatSend");

  const UPSTAGE_API_URL = "https://api.upstage.ai/v1/chat/completions";
  const UPSTAGE_MODEL = "solar-pro3";
  const API_KEY_STORAGE = "upstage-api-key";
  const IS_LOCAL_FILE = location.protocol === "file:";

  var conversationHistory = [];
  var isSending = false;


  /* ---------- 패널 열기/닫기 ---------- */
  function openChatPanel() {
    if (!chatPanel || !chatFab) return;
    chatPanel.classList.add("is-open");
    chatPanel.setAttribute("aria-hidden", "false");
    chatFab.classList.add("is-hidden");
    chatFab.setAttribute("aria-expanded", "true");
    if (chatInput) chatInput.focus();
  }

  function closeChatPanel() {
    if (!chatPanel || !chatFab) return;
    chatPanel.classList.remove("is-open");
    chatPanel.setAttribute("aria-hidden", "true");
    chatFab.classList.remove("is-hidden");
    chatFab.setAttribute("aria-expanded", "false");
  }

  if (chatFab) {
    chatFab.addEventListener("click", openChatPanel);
  }

  if (chatClose) {
    chatClose.addEventListener("click", closeChatPanel);
  }


  /* ---------- 메시지 UI ---------- */
  function appendMessage(text, type) {
    if (!chatMessages) return null;

    var div = document.createElement("div");
    div.className = "chatbot__message chatbot__message--" + type;

    if (type === "loading") {
      div.innerHTML =
        '<div class="chatbot__typing" aria-label="응답 생성 중">' +
        "<span></span><span></span><span></span>" +
        "</div>";
    } else {
      var p = document.createElement("p");
      p.textContent = text;
      div.appendChild(p);
    }

    chatMessages.appendChild(div);
    chatMessages.scrollTop = chatMessages.scrollHeight;
    return div;
  }

  function removeMessage(el) {
    if (el && el.parentNode) {
      el.parentNode.removeChild(el);
    }
  }

  function setSendingState(active) {
    isSending = active;
    if (chatSend) chatSend.disabled = active;
    if (chatInput) chatInput.disabled = active;
  }


  /* ---------- 로컬 file: 환경 — API 키 관리 ---------- */
  function getLocalApiKey() {
    return localStorage.getItem(API_KEY_STORAGE);
  }

  function saveLocalApiKey(key) {
    localStorage.setItem(API_KEY_STORAGE, key);
  }

  function clearLocalApiKey() {
    localStorage.removeItem(API_KEY_STORAGE);
  }

  function promptForApiKey() {
    var key = window.prompt("Upstage API 키를 붙여넣어 주세요 (up_으로 시작)");
    if (key && key.trim()) {
      saveLocalApiKey(key.trim());
      return key.trim();
    }
    return null;
  }


  /* ---------- API 요청 — 환경별 분기 ---------- */
  function buildMessagesPayload() {
    return [{ role: "system", content: SYSTEM_PROMPT }].concat(conversationHistory);
  }

  async function callUpstageDirect(messages, apiKey) {
    var response = await fetch(UPSTAGE_API_URL, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: "Bearer " + apiKey,
      },
      body: JSON.stringify({
        model: UPSTAGE_MODEL,
        messages: messages,
      }),
    });

    var data = await response.json();
    return { response: response, data: data };
  }

  async function callUpstageViaProxy(messages) {
    var response = await fetch("/api/chat", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ messages: messages }),
    });

    var data = await response.json();
    return { response: response, data: data };
  }

  async function requestChatCompletion(messages) {
    if (IS_LOCAL_FILE) {
      var apiKey = getLocalApiKey();

      if (!apiKey) {
        apiKey = promptForApiKey();
        if (!apiKey) {
          throw { type: "cancelled" };
        }
      }

      var result = await callUpstageDirect(messages, apiKey);

      if (result.response.status === 401) {
        clearLocalApiKey();
        throw { type: "auth" };
      }

      return result;
    }

    return callUpstageViaProxy(messages);
  }

  function extractAssistantReply(data) {
    if (
      data &&
      data.choices &&
      data.choices[0] &&
      data.choices[0].message &&
      data.choices[0].message.content
    ) {
      return data.choices[0].message.content.trim();
    }
    return null;
  }


  /* ---------- 메시지 전송 ---------- */
  async function sendMessage() {
    if (!chatInput || isSending) return;

    var text = chatInput.value.trim();
    if (!text) return;

    appendMessage(text, "user");
    conversationHistory.push({ role: "user", content: text });
    chatInput.value = "";
    chatInput.style.height = "auto";

    setSendingState(true);
    var loadingEl = appendMessage("", "loading");

    try {
      var messages = buildMessagesPayload();
      var result = await requestChatCompletion(messages);
      removeMessage(loadingEl);

      if (!result.response.ok) {
        appendMessage("잠시 후 다시 시도해 주세요.", "error");
        conversationHistory.pop();
        return;
      }

      var reply = extractAssistantReply(result.data);

      if (!reply) {
        appendMessage("잠시 후 다시 시도해 주세요.", "error");
        conversationHistory.pop();
        return;
      }

      appendMessage(reply, "bot");
      conversationHistory.push({ role: "assistant", content: reply });
    } catch (err) {
      removeMessage(loadingEl);

      if (err && err.type === "auth") {
        appendMessage(
          "키가 올바르지 않아요. 다시 질문하시면 새로 입력받을게요.",
          "error"
        );
        conversationHistory.pop();
      } else if (err && err.type === "cancelled") {
        conversationHistory.pop();
      } else {
        appendMessage("잠시 후 다시 시도해 주세요.", "error");
        conversationHistory.pop();
      }
    } finally {
      setSendingState(false);
      if (chatInput) chatInput.focus();
    }
  }


  /* ---------- 폼 이벤트 ---------- */
  if (chatForm) {
    chatForm.addEventListener("submit", function (event) {
      event.preventDefault();
      sendMessage();
    });
  }

  if (chatInput) {
    chatInput.addEventListener("keydown", function (event) {
      if (event.key === "Enter" && !event.shiftKey) {
        event.preventDefault();
        sendMessage();
      }
    });

    chatInput.addEventListener("input", function () {
      chatInput.style.height = "auto";
      chatInput.style.height = Math.min(chatInput.scrollHeight, 100) + "px";
    });
  }

})();
